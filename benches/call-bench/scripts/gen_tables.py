"""Generate the HPACK/QPACK static tables and the Huffman code from RFC text.

Usage: python3 gen_tables.py rfc7541.txt rfc9204.txt > ../src/tables.rs
with the plain-text RFCs from https://www.rfc-editor.org/rfc/.
"""
import re, sys
rfc7541 = open(sys.argv[1]).read()
rfc9204 = open(sys.argv[2]).read()

def body_lines(text, start, end):
    begin = text.rindex(start)
    lines = text[begin:text.index(end, begin)].splitlines()
    out = []
    for line in lines:
        if line.startswith('\f') or re.match(r'^(RFC \d+|Peon|Krasic)', line.strip()) or 'et al.' in line and 'Standards Track' in line:
            continue
        out.append(line)
    return out

def parse_table(lines, wrap_rows):
    rows, current = [], None
    for line in lines:
        s = line.strip()
        if not s.startswith('|'):
            if s.startswith('+') and current is not None and wrap_rows:
                rows.append(current); current = None
            continue
        cells = [c.strip() for c in s.strip('|').split('|')]
        if len(cells) != 3:
            continue
        if cells[0].isdigit():
            if current is not None:
                rows.append(current)
            current = [int(cells[0]), [cells[1]], [cells[2]]]
            if not wrap_rows:
                rows.append(current); current = None
        elif current is not None and cells[0] == '':
            current[1].append(cells[1]); current[2].append(cells[2])
    if current is not None:
        rows.append(current)
    out = []
    for index, name, value in rows:
        name = ''.join(p for p in name if p)
        parts = [p for p in value if p]
        if len(parts) > 1:
            print(f'wrapped {index}: {parts!r}', file=sys.stderr)
        # Cells wrap at a space, or after a hyphen or slash inside a token.
        joined = ''
        for part in parts:
            joined += part if not joined or joined.endswith(('-', '/')) else ' ' + part
        out.append((index, name, joined))
    return out

hpack = parse_table(body_lines(rfc7541, 'Appendix A.  Static Table Definition', 'Appendix B.  Huffman Code'), False)
qpack = parse_table(body_lines(rfc9204, 'Appendix A.  Static Table', 'Appendix B.  Encoding and Decoding Examples'), True)
assert [r[0] for r in hpack] == list(range(1, 62)), [r[0] for r in hpack]
assert [r[0] for r in qpack] == list(range(0, 99)), [r[0] for r in qpack]

huffman = {}
for m in re.finditer(r'\(\s*(\d+)\)\s+((?:\|[01]+)+)\s+([0-9a-f]+)\s+\[\s*(\d+)\]', rfc7541):
    symbol, bits, hexcode, length = int(m[1]), m[2].replace('|', ''), int(m[3], 16), int(m[4])
    assert int(bits, 2) == hexcode and len(bits) == length, m[0]
    huffman[symbol] = (hexcode, length)
assert sorted(huffman) == list(range(257))

def rs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

print('//! Generated by `gen_tables.py` from the text of RFC 7541 (Appendix A,')
print('//! the HPACK static table; Appendix B, the Huffman code) and RFC 9204')
print('//! (Appendix A, the QPACK static table). Do not edit.')
print()
print('/// HPACK static table; entry `i` has index `i + 1`.')
print('pub const HPACK_STATIC: [(&str, &str); 61] = [')
for _, n, v in hpack:
    print(f'    ({rs(n)}, {rs(v)}),')
print('];')
print()
print('/// QPACK static table; entry `i` has index `i`.')
print('pub const QPACK_STATIC: [(&str, &str); 99] = [')
for _, n, v in qpack:
    print(f'    ({rs(n)}, {rs(v)}),')
print('];')
print()
print('/// The Huffman code of each symbol, with its length in bits; symbol 256 is EOS.')
print('pub const HUFFMAN: [(u32, u8); 257] = [')
for s in range(257):
    c, l = huffman[s]
    print(f'    (0x{c:x}, {l}),')
print('];')
