/// What an operation produces over family `F`, or over the families of a
/// tuple, independent of the access it runs with: neither type can carry the
/// access or its brand.
pub trait Operation<F: Receivers> {
    /// The final value.
    type Output;
    /// Intermediate items; `Infallible` for operations that emit none.
    type Yield;
}

/// Starting an operation with an access, or a tuple of accesses.
///
/// A [`Call`] over family `F` requires `for<'s> Start<'s, ReceiverSlot<'s,
/// F>>`, and over a tuple of families the tuple of their slots, so the
/// operation must accept every brand. A call is `Send` when the operation's
/// future is.
pub trait Start<'s, A: Accesses>: Operation<A::Families> {
    type Fut: Future<Output = <Self as Operation<A::Families>>::Output>;
    fn start(
        self,
        access: A,
        emitter: Emitter<'s, <Self as Operation<A::Families>>::Yield>,
    ) -> Self::Fut;
}

/// An operation that can run as the root of a call on `R`, a family or a
/// tuple of them: every operation generated by `#[call]` or `#[capability]`
/// for that family. It abbreviates the bounds that [`Call`] and executors
/// require.
pub trait RootOperation<R: Receivers>: Operation<R> + for<'s> Start<'s, R::Slots<'s>> {}
impl<R: Receivers, Op> RootOperation<R> for Op where
    Op: Operation<R> + for<'s> Start<'s, R::Slots<'s>>
{
}

/// Where an operation's emitted item waits for its caller, and whether the
/// current poll discards items instead.
pub(crate) struct ItemCell<Y> {
    item: Cell<Option<Y>>,
    discard: Cell<bool>,
    /// The waker of the current poll; null outside one.
    root: RootWaker,
}
impl<Y> ItemCell<Y> {
    pub(crate) fn new() -> Self {
        Self {
            item: Cell::new(None),
            discard: Cell::new(false),
            root: RootWaker::new(),
        }
    }
    pub(crate) fn set_discard(&self, discard: bool) {
        self.discard.set(discard);
    }
}

/// Emits intermediate items from an operation. `#[call(yields = T)]` turns
/// each `yield` of the function into an emission.
pub struct Emitter<'s, Y> {
    cell: *const ItemCell<Y>,
    brand: PhantomData<fn(&'s ()) -> &'s ()>,
}
// SAFETY: the item cell is read only after the operation's poll returns, so
// an emitter moved to another thread during that poll never races with it.
// Items cross threads, hence `Y: Send`.
unsafe impl<Y: Send> Send for Emitter<'_, Y> {}
// SAFETY: shared references expose nothing.
unsafe impl<Y> Sync for Emitter<'_, Y> {}
impl<Y> fmt::Debug for Emitter<'_, Y> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Emitter").finish_non_exhaustive()
    }
}
impl<Y> Emitter<'_, Y> {
    pub(crate) fn new(cell: &ItemCell<Y>) -> Self {
        Self {
            cell,
            brand: PhantomData,
        }
    }
    /// Hand `item` to whoever polls the operation. Completes on the poll after
    /// the item has been delivered; dropping it after the first poll still
    /// delivers it. When the caller discards items, drops `item` and
    /// completes at once.
    pub fn emit(&mut self, item: Y) -> impl Future<Output = ()> + '_ {
        let mut item = Some(item);
        poll_fn(move |cx| {
            let Some(pending) = item.take() else {
                return Poll::Ready(());
            };
            // SAFETY: the owner of the cell outlives its operation.
            let cell = unsafe { &*self.cell };
            if cell.discard.get() {
                return Poll::Ready(());
            }
            match cell.item.take() {
                // An earlier emission in this poll is not yet delivered.
                Some(earlier) => {
                    cell.item.set(Some(earlier));
                    item = Some(pending);
                }
                None => cell.item.set(Some(pending)),
            }
            // Intermediate executors only repoll branches whose waker fired.
            // With none, the item itself makes the poll ready.
            if !polled_directly(cell.root.get(), cx) {
                cx.waker().wake_by_ref();
            }
            Poll::Pending
        })
    }
}
impl Emitter<'_, Infallible> {
    /// An emitter for operations that emit nothing; it has no cell.
    pub(crate) fn detached() -> Self {
        Self {
            cell: ptr::null(),
            brand: PhantomData,
        }
    }
}

/// The result of polling a call.
#[derive(Debug, PartialEq, Eq)]
pub enum CallPoll<T> {
    Ready(T),
    Pending,
    /// The call was polled without a view, and its operation asked for one
    /// in this poll or an earlier one that had none either. Nothing else
    /// wakes the call for this: poll it again with a view, or arrange a
    /// wakeup for when one is available.
    NeedsView,
    /// The call was lent a releasable view, and its operation reached a
    /// release point: it does not need the view for a while. Poll the call
    /// again, without the view to release it or with the same view to keep
    /// it; either way the release point completes. Nothing else wakes the
    /// call for this.
    Releasable,
}
impl<T> CallPoll<T> {
    /// Treat a request for a view as a bug: for callers that always lend a
    /// fixed one.
    pub(crate) fn lent(self) -> Poll<T> {
        match self {
            CallPoll::Ready(value) => Poll::Ready(value),
            CallPoll::Pending => Poll::Pending,
            CallPoll::NeedsView => unreachable!("a call given a view asked for one"),
            CallPoll::Releasable => unreachable!("a call given a fixed view offered it back"),
        }
    }
}

/// A view lent to a call, and whether the lender may take it back at a
/// release point of the operation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lend<V> {
    /// Kept for the whole poll: release points complete at once.
    Fixed(V),
    /// The lender may release it where the operation offers it back; the
    /// call then returns [`CallPoll::Releasable`].
    Releasable(V),
}
impl<V> Lend<V> {
    pub fn into_inner(self) -> V {
        match self {
            Lend::Fixed(view) | Lend::Releasable(view) => view,
        }
    }
    pub fn is_releasable(&self) -> bool {
        matches!(self, Lend::Releasable(_))
    }
    pub fn map<U>(self, f: impl FnOnce(V) -> U) -> Lend<U> {
        match self {
            Lend::Fixed(view) => Lend::Fixed(f(view)),
            Lend::Releasable(view) => Lend::Releasable(f(view)),
        }
    }
    pub fn as_mut(&mut self) -> Lend<&mut V> {
        match self {
            Lend::Fixed(view) => Lend::Fixed(view),
            Lend::Releasable(view) => Lend::Releasable(view),
        }
    }
    pub fn as_pin_mut(self: Pin<&mut Self>) -> Lend<Pin<&mut V>> {
        // SAFETY: the view is pinned whenever the lend is; it is never moved
        // out of a pinned lend.
        unsafe {
            match self.get_unchecked_mut() {
                Lend::Fixed(view) => Lend::Fixed(Pin::new_unchecked(view)),
                Lend::Releasable(view) => Lend::Releasable(Pin::new_unchecked(view)),
            }
        }
    }
}

/// Clears the lent views at the end of a poll, and poisons the call when the
/// poll panics.
struct LendGuard<'a, R: Receivers> {
    cells: &'a R::Cells,
    poisoned: &'a Cell<bool>,
}
impl<R: Receivers> Drop for LendGuard<'_, R> {
    fn drop(&mut self) {
        self.cells.clear();
        if std::thread::panicking() {
            self.poisoned.set(true);
        }
    }
}

/// The waker the operation of a call sees once a branch of an intermediate
/// executor has waited for a view or for the answer to an offer.
///
/// A branch that waits is not woken then: its slot keeps its waker, and the
/// call wakes it when the slot is lent a view or answered, right before
/// polling the operation. The executor then wakes the waker it was polled
/// with; for this call that is the intercepting waker, which drops wakes
/// caused by that replay, since the operation is polled next, and passes
/// other wakes to the caller.
pub(crate) struct Intercept {
    caller: Mutex<Option<Waker>>,
}

thread_local! {
    /// The interception state of the call whose branches this thread is
    /// waking before polling its operation; null otherwise.
    static REPLAYING: Cell<*const Intercept> = const { Cell::new(ptr::null()) };
}

impl Intercept {
    fn new() -> Self {
        Self {
            caller: Mutex::new(None),
        }
    }
    /// Wake `branches`. The wakes this causes synchronously at this call's
    /// intercepting waker are dropped; wakes reaching other calls are not.
    fn replay(self: &Arc<Self>, branches: Vec<Waker>) {
        struct Restore(*const Intercept);
        impl Drop for Restore {
            fn drop(&mut self) {
                REPLAYING.set(self.0);
            }
        }
        let _restore = Restore(REPLAYING.replace(Arc::as_ptr(self)));
        for branch in branches {
            branch.wake();
        }
    }
    fn set_caller(&self, waker: &Waker) {
        let mut caller = self.caller.lock().unwrap_or_else(PoisonError::into_inner);
        if !caller
            .as_ref()
            .is_some_and(|caller| caller.will_wake(waker))
        {
            *caller = Some(waker.clone());
        }
    }
    fn wake_caller(&self) {
        let caller = self.caller.lock().unwrap_or_else(PoisonError::into_inner);
        if let Some(caller) = &*caller {
            caller.wake_by_ref();
        }
    }
}
impl Wake for Intercept {
    fn wake(self: Arc<Self>) {
        self.wake_by_ref();
    }
    fn wake_by_ref(self: &Arc<Self>) {
        if !ptr::eq(REPLAYING.get(), Arc::as_ptr(self)) {
            self.wake_caller();
        }
    }
}

/// Storage for a value pinned in place that may hold references into itself,
/// such as a running future. Safe code can take a shared reference to a
/// pinned owner through `Pin`; without the cell that reference would assert
/// that the value is not mutated, invalidating those references. Replace with
/// `UnsafePinned` once it is stable.
pub(crate) struct InPlace<T>(UnsafeCell<T>);
impl<T> InPlace<T> {
    pub(crate) fn new(value: T) -> Self {
        Self(UnsafeCell::new(value))
    }
    pub(crate) fn get_mut(&mut self) -> &mut T {
        self.0.get_mut()
    }
    pub(crate) fn get_pin_mut(self: Pin<&mut Self>) -> Pin<&mut T> {
        // SAFETY: the value is pinned whenever its storage is.
        unsafe { self.map_unchecked_mut(|this| this.0.get_mut()) }
    }
}

/// The size hint of an operation's events: at least the final value until it
/// has been delivered.
pub(crate) fn remaining(terminated: bool) -> (usize, Option<usize>) {
    match terminated {
        true => (0, Some(0)),
        false => (1, None),
    }
}

pub(crate) enum State<Op, Fut, R> {
    Start(Op),
    Running(Fut),
    /// Finished while an emitted item was still undelivered.
    Returned(R),
    Finished,
}

/// Advance an operation's state by one event: an emitted item comes before
/// the result.
///
/// # Safety
/// `state` must be pinned: a running future is never moved.
#[inline]
pub(crate) unsafe fn step_operation<Op, Fut: Future, Y>(
    state: &mut State<Op, Fut, Fut::Output>,
    emitted: &ItemCell<Y>,
    start: impl FnOnce(Op) -> Fut,
    cx: &mut Context<'_>,
) -> Poll<ControlFlow<Fut::Output, Y>> {
    match state {
        State::Start(_) => {
            let State::Start(operation) = mem::replace(state, State::Finished) else {
                unreachable!()
            };
            *state = State::Running(start(operation));
        }
        State::Running(_) => {}
        State::Returned(_) => {
            let State::Returned(result) = mem::replace(state, State::Finished) else {
                unreachable!()
            };
            return Poll::Ready(ControlFlow::Break(result));
        }
        State::Finished => panic!("operation polled after completion"),
    }
    let State::Running(future) = state else {
        unreachable!()
    };
    /// Clears the root waker when the poll ends.
    struct Root<'a>(&'a RootWaker);
    impl Drop for Root<'_> {
        fn drop(&mut self) {
            self.0.clear();
        }
    }
    emitted.root.set(cx.waker());
    let root = Root(&emitted.root);
    // SAFETY: the caller keeps the state pinned.
    let poll = unsafe { Pin::new_unchecked(future) }.poll(cx);
    drop(root);
    match poll {
        Poll::Ready(result) => {
            *state = State::Finished;
            match emitted.item.take() {
                Some(item) => {
                    *state = State::Returned(result);
                    Poll::Ready(ControlFlow::Continue(item))
                }
                None => Poll::Ready(ControlFlow::Break(result)),
            }
        }
        Poll::Pending => match emitted.item.take() {
            Some(item) => Poll::Ready(ControlFlow::Continue(item)),
            None => Poll::Pending,
        },
    }
}

type Running<R, Op> = <Op as Start<'static, <R as Receivers>::Slots<'static>>>::Fut;
type Output<R, Op> = <Op as Operation<R>>::Output;
type Yield<R, Op> = <Op as Operation<R>>::Yield;
type CallState<R, Op> = State<Op, Running<R, Op>, Output<R, Op>>;

/// An operation and its cells, polled with views supplied by the caller on
/// each poll.
///
/// The views may differ between polls, so a call can be stored apart from
/// the resources it uses. A caller that acquires lazily polls without a view;
/// the call asks for one when its operation first uses it. A call has two
/// forms: [`poll_with`](Self::poll_with) delivers each emitted item and then
/// the final value, and [`poll_return_with`](Self::poll_return_with) discards
/// the items.
///
/// A call over a tuple of families gives its operation a slot for each, and
/// is polled with [`poll_with_views`](Self::poll_with_views): each slot is
/// lent a view, or not, on its own.
pub struct Call<R, Op>
where
    R: Receivers,
    Op: Operation<R> + for<'s> Start<'s, R::Slots<'s>>,
{
    // Dropped before the cells its future points into.
    state: InPlace<CallState<R, Op>>,
    cells: R::Cells,
    /// Present once a branch of an intermediate executor has waited for a
    /// view or an answer.
    intercept: OnceCell<Arc<Intercept>>,
    emitted: ItemCell<Yield<R, Op>>,
    poisoned: Cell<bool>,
    finished: bool,
    _pinned: PhantomPinned,
}
// SAFETY: the bounds cover everything the call keeps besides its cells: the
// operation, its future for every brand, and its results. Between polls no
// view cell lends a view and the root wakers are null, so moving the cells
// moves no view or borrowed waker; the intercepting state is shared through
// an `Arc` and synchronized.
unsafe impl<R, Op> Send for Call<R, Op>
where
    R: Receivers,
    Op: Operation<R> + Send + for<'s> Start<'s, R::Slots<'s>>,
    for<'s> <Op as Start<'s, R::Slots<'s>>>::Fut: Send,
    Output<R, Op>: Send,
    Yield<R, Op>: Send,
{
}
// SAFETY: a shared reference only reads whether the call has finished, which
// changes only through `Pin<&mut Self>`, and the flags of its cells, which
// change only while the call is polled.
unsafe impl<R, Op> Sync for Call<R, Op>
where
    R: Receivers,
    Op: Operation<R> + for<'s> Start<'s, R::Slots<'s>>,
{
}
impl<R, Op> fmt::Debug for Call<R, Op>
where
    R: Receivers,
    Op: Operation<R> + for<'s> Start<'s, R::Slots<'s>>,
{
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Call")
            .field("terminated", &self.finished)
            .finish_non_exhaustive()
    }
}

impl<R, Op> Call<R, Op>
where
    R: Receivers,
    Op: Operation<R> + for<'s> Start<'s, R::Slots<'s>>,
{
    /// Prepare a call. The operation starts on the first poll.
    pub fn new(operation: Op) -> Self {
        Self {
            state: InPlace::new(State::Start(operation)),
            cells: R::Cells::new(),
            intercept: OnceCell::new(),
            emitted: ItemCell::new(),
            poisoned: Cell::new(false),
            finished: false,
            _pinned: PhantomPinned,
        }
    }

    /// Whether the call has delivered its final value and must not be polled
    /// again.
    pub fn is_terminated(&self) -> bool {
        self.finished
    }

    /// Which slots need a view, as of the last poll: their operation asked
    /// for one, or a branch still waits for one.
    pub fn views_needed(&self) -> R::Flags {
        self.cells.needed()
    }

    /// Which slots offered their view back at a release point in the last
    /// poll; the next poll answers by lending it again or not.
    pub fn views_offered(&self) -> R::Flags {
        self.cells.offered()
    }

    /// Advance the operation with this poll's views, one for each slot that
    /// the caller lends. `Continue` holds an emitted item and `Break` the
    /// final value, after which the call is done. The call needs a view when
    /// some slot does, and is releasable when some slot offered its view
    /// back; [`views_needed`](Self::views_needed) and
    /// [`views_offered`](Self::views_offered) tell which.
    #[inline]
    pub fn poll_with_views(
        self: Pin<&mut Self>,
        lends: R::Lends<'_>,
        cx: &mut Context<'_>,
    ) -> CallPoll<ControlFlow<Output<R, Op>, Yield<R, Op>>> {
        self.poll_step(lends, false, cx)
    }

    /// Advance to the final value with this poll's views. Emitted items are
    /// dropped where they are emitted, without suspending the operation.
    #[inline]
    pub fn poll_return_with_views(
        self: Pin<&mut Self>,
        lends: R::Lends<'_>,
        cx: &mut Context<'_>,
    ) -> CallPoll<Output<R, Op>> {
        match self.poll_step(lends, true, cx) {
            CallPoll::Ready(ControlFlow::Break(result)) => CallPoll::Ready(result),
            CallPoll::Ready(ControlFlow::Continue(_)) => {
                unreachable!("discarded items are not stored")
            }
            CallPoll::Pending => CallPoll::Pending,
            CallPoll::NeedsView => CallPoll::NeedsView,
            CallPoll::Releasable => CallPoll::Releasable,
        }
    }

    #[inline]
    fn poll_step(
        self: Pin<&mut Self>,
        lends: R::Lends<'_>,
        discard: bool,
        cx: &mut Context<'_>,
    ) -> CallPoll<ControlFlow<Output<R, Op>, Yield<R, Op>>> {
        // SAFETY: nothing is moved out of the pinned call; the running future
        // is pinned in place until it is dropped in place. The future keeps
        // pointers into the cells, so they are only accessed through shared
        // references.
        let this = unsafe { self.get_unchecked_mut() };
        let (cells, intercept, emitted, poisoned, state) = (
            &this.cells,
            &this.intercept,
            &this.emitted,
            &this.poisoned,
            this.state.get_mut(),
        );
        if let State::Finished = state {
            panic!("call polled after completion");
        }
        assert!(!poisoned.get(), "call polled after a panic");
        emitted.set_discard(discard);
        // Once a branch has waited for a view or an answer, the operation
        // sees the intercepting waker. The operation is polled with a context
        // of its own either way: a single path keeps the common case as fast
        // as before, and the caller's context carries nothing else on stable
        // Rust.
        let intercepting = intercept
            .get()
            .map(|intercept| intercepting_waker(intercept, cx.waker()));
        let guard = LendGuard::<R> { cells, poisoned };
        // Branches wait only once the call intercepts: it starts to after
        // the first poll in which one asked. Lending with that known lets
        // the common path skip the checks for waiting branches.
        // SAFETY: the lends outlive this function, whose guard clears them.
        let waker = match &intercepting {
            None => {
                unsafe { cells.lend(lends, cx.waker(), false) };
                cx.waker()
            }
            Some(waker) => {
                // A view, or the answer to an offer, wakes the branches
                // waiting for that slot.
                if unsafe { cells.lend(lends, waker, true) } {
                    replay::<R>(intercept, cells);
                }
                waker
            }
        };
        let start = |operation: Op| {
            // SAFETY: the call is pinned, so the cells keep their address, and
            // the future holding the slots and the emitter is dropped before
            // them. `Op: for<'s> Start` keeps the operation from relying on
            // the 'static brand chosen for storage, and from moving a slot
            // out of its future.
            let slots: R::Slots<'static> = unsafe { cells.slots() };
            operation.start(slots, Emitter::new(emitted))
        };
        // SAFETY: the state is a field of the pinned call.
        let poll =
            unsafe { step_operation(state, emitted, start, &mut Context::from_waker(waker)) };
        drop(guard);
        // Even a poll that emits an item may leave a branch waiting.
        if intercepting.is_none() && cells.waiting() {
            intercept.get_or_init(|| Arc::new(Intercept::new()));
        }
        let poll = match poll {
            // A release point reached in the poll that emits an item is
            // answered by the next poll like an offer.
            Poll::Ready(value) => CallPoll::Ready(value),
            // Only lent slots reach release points, and only slots without a
            // view ask for one. A branch that asked on an earlier poll still
            // waits for a view.
            Poll::Pending if <R::Cells as CellSet<R>>::any(cells.offered()) => CallPoll::Releasable,
            Poll::Pending if <R::Cells as CellSet<R>>::any(cells.needed()) => CallPoll::NeedsView,
            Poll::Pending => CallPoll::Pending,
        };
        this.finished = matches!(poll, CallPoll::Ready(ControlFlow::Break(_)));
        poll
    }
}

impl<F, Op> Call<F, Op>
where
    F: ReceiverFamily,
    Op: Operation<F> + for<'s> Start<'s, ReceiverSlot<'s, F>>,
{
    /// Advance the operation with this poll's view, if the caller has one.
    /// `Continue` holds an emitted item and `Break` the final value, after
    /// which the call is done.
    pub fn poll_with<'view>(
        self: Pin<&mut Self>,
        view: Option<Lend<Pin<&mut F::ReceiverView<'view>>>>,
        cx: &mut Context<'_>,
    ) -> CallPoll<ControlFlow<Output<F, Op>, Yield<F, Op>>>
    where
        F: 'view,
    {
        self.poll_with_views(lent::<F>(view), cx)
    }

    /// Advance to the final value with this poll's view. Emitted items are
    /// dropped where they are emitted, without suspending the operation.
    pub fn poll_return_with<'view>(
        self: Pin<&mut Self>,
        view: Option<Lend<Pin<&mut F::ReceiverView<'view>>>>,
        cx: &mut Context<'_>,
    ) -> CallPoll<Output<F, Op>>
    where
        F: 'view,
    {
        self.poll_return_with_views(lent::<F>(view), cx)
    }
}

/// The intercepting waker of a call, forwarding to `caller`.
#[cold]
fn intercepting_waker(intercept: &Arc<Intercept>, caller: &Waker) -> Waker {
    intercept.set_caller(caller);
    Waker::from(intercept.clone())
}

/// Wake the branches answered by this poll.
#[cold]
fn replay<R: Receivers>(intercept: &OnceCell<Arc<Intercept>>, cells: &R::Cells) {
    let mut answered = Vec::new();
    cells.take_answered(&mut answered);
    intercept
        .get()
        .expect("branches wait only while the call intercepts")
        .replay(answered);
}

/// The dyn-compatible interface of [`Call`], for storing calls of different
/// types over the same receivers.
pub trait DynCall<R: Receivers, Y, Out> {
    fn poll_with_views(
        self: Pin<&mut Self>,
        lends: R::Lends<'_>,
        cx: &mut Context<'_>,
    ) -> CallPoll<ControlFlow<Out, Y>>;
    fn poll_return_with_views(
        self: Pin<&mut Self>,
        lends: R::Lends<'_>,
        cx: &mut Context<'_>,
    ) -> CallPoll<Out>;
    fn views_needed(&self) -> R::Flags;
    fn views_offered(&self) -> R::Flags;
    fn poll_with<'view>(
        self: Pin<&mut Self>,
        view: Option<Lend<Pin<&mut <R as ReceiverFamily>::ReceiverView<'view>>>>,
        cx: &mut Context<'_>,
    ) -> CallPoll<ControlFlow<Out, Y>>
    where
        R: ReceiverFamily + 'view;
    fn poll_return_with<'view>(
        self: Pin<&mut Self>,
        view: Option<Lend<Pin<&mut <R as ReceiverFamily>::ReceiverView<'view>>>>,
        cx: &mut Context<'_>,
    ) -> CallPoll<Out>
    where
        R: ReceiverFamily + 'view;
}
impl<R, Op> DynCall<R, Yield<R, Op>, Output<R, Op>> for Call<R, Op>
where
    R: Receivers,
    Op: Operation<R> + for<'s> Start<'s, R::Slots<'s>>,
{
    fn poll_with_views(
        self: Pin<&mut Self>,
        lends: R::Lends<'_>,
        cx: &mut Context<'_>,
    ) -> CallPoll<ControlFlow<Output<R, Op>, Yield<R, Op>>> {
        Call::poll_with_views(self, lends, cx)
    }
    fn poll_return_with_views(
        self: Pin<&mut Self>,
        lends: R::Lends<'_>,
        cx: &mut Context<'_>,
    ) -> CallPoll<Output<R, Op>> {
        Call::poll_return_with_views(self, lends, cx)
    }
    fn views_needed(&self) -> R::Flags {
        Call::views_needed(self)
    }
    fn views_offered(&self) -> R::Flags {
        Call::views_offered(self)
    }
    fn poll_with<'view>(
        self: Pin<&mut Self>,
        view: Option<Lend<Pin<&mut <R as ReceiverFamily>::ReceiverView<'view>>>>,
        cx: &mut Context<'_>,
    ) -> CallPoll<ControlFlow<Output<R, Op>, Yield<R, Op>>>
    where
        R: ReceiverFamily + 'view,
    {
        self.poll_with_views(lent::<R>(view), cx)
    }
    fn poll_return_with<'view>(
        self: Pin<&mut Self>,
        view: Option<Lend<Pin<&mut <R as ReceiverFamily>::ReceiverView<'view>>>>,
        cx: &mut Context<'_>,
    ) -> CallPoll<Output<R, Op>>
    where
        R: ReceiverFamily + 'view,
    {
        self.poll_return_with_views(lent::<R>(view), cx)
    }
}

/// The lend of a single family for a view pinned by its lender.
fn lent<'a, 'view: 'a, F: ReceiverFamily + 'view>(
    view: Option<Lend<Pin<&'a mut F::ReceiverView<'view>>>>,
) -> <F as Receivers>::Lends<'a> {
    <F as Single>::lend(view)
}
